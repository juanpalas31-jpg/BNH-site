import { weaveWeb,nextHuntPlan } from "./atila-web-weaver.js";

export function runAttilaHuntCycle({pages=[],events=[],leads=[],previous={}}={}){
 const plan=nextHuntPlan({pages,events,leads,previous});
 const evidence={
  event_count:events.length,lead_count:leads.length,page_count:pages.length,
  sufficient_signal:events.length>=8||leads.length>=1
 };
 if(!evidence.sufficient_signal){
  return {state:"WEB_LISTEN",evidence,plan:{...plan,action:"COLLECT_SIGNAL"},execute:false,
   reason:"Attila needs measured signal before changing the web."};
 }
 return {state:"HUNT_PLAN_READY",evidence,plan,execute:false,
  reason:"Plan is generated by Attila; publication remains gated until validated."};
}

export function evaluateHuntOutcome({before={},after={}}={}){
 const b=Number(before.leads||0),a=Number(after.leads||0);
 const bv=Number(before.views||0),av=Number(after.views||0);
 const br=b/Math.max(1,bv),ar=a/Math.max(1,av);
 const delta=ar-br;
 return {
  evaluator:"ATTILA_ADAPTIVE_FEEDBACK",
  outcome:delta>0?"REINFORCE":delta<0?"RECONSIDER":"KEEP_OBSERVING",
  conversion_before:Number(br.toFixed(4)),conversion_after:Number(ar.toFixed(4)),
  delta:Number(delta.toFixed(4)),
  durable_learning:Math.abs(delta)>=0.01&&av>=8,
  doctrine:["MEASURE","UNDERSTAND","CORRECT","MEMORIZE","EVOLVE"]
 };
}
